"""
Backend LSTM Multivariate Log-Return Prediction & Evaluation Module
Project: Stock-AI - Professional NSE Stock Price Prediction & Live Intelligence Dashboard

Architecture:
- Stationary Feature Engineering:
    1. Log_Return: np.log(Close / Close.shift(1))
    2. RSI_14: 14-period Relative Strength Index (Wilder's Smoothing)
    3. SMA_20_Ratio: Close / Close.rolling(20).mean()
    4. Volatility_10: Log_Return.rolling(10).std()
- Stationary Prediction Target:
    Target_Next_Return: Log_Return.shift(-1) (Return of trading day T+1)
- Multivariate Scaling:
    feature_scaler: MinMaxScaler(0, 1) on 4 input features
    target_scaler: MinMaxScaler(-1, 1) on next-day log return
- Sequence Generation: (samples, 60, 4)
- Mathematically Grounded Price Reconstruction:
    Tomorrow_Predicted_Price = live_price * np.exp(predicted_log_return)
"""

