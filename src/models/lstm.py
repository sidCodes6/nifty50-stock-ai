DATA_RAW_DIR = os.path.join(PROJECT_ROOT, "data", "raw")
DATA_PROCESSED_DIR = os.path.join(PROJECT_ROOT, "data", "processed")
MODELS_DIR = os.path.join(PROJECT_ROOT, "models")

for directory in [DATA_RAW_DIR, DATA_PROCESSED_DIR, MODELS_DIR]:
    os.makedirs(directory, exist_ok=True)

FEATURE_COLS = ["Log_Return", "RSI_14", "SMA_20_Ratio", "Volatility_10"]
TARGET_COL = "Target_Next_Return"
# Increment whenever training labels, feature order, or inference semantics change.
ARTIFACT_VERSION = 2


def clean_market_data(df: pd.DataFrame, ticker: str = "^NSEI") -> pd.DataFrame:
    """
    Cleans market data downloaded from yfinance.
    Handles MultiIndex columns safely so df['Close'] never throws a shape or key error.
    """
    if df is None or df.empty:
        raise ValueError(f"No market data returned for ticker: {ticker}")

    df_cleaned = df.copy()

    # Flatten MultiIndex columns
    if isinstance(df_cleaned.columns, pd.MultiIndex):
        found = False
        for level in range(df_cleaned.columns.nlevels):
            level_values = df_cleaned.columns.get_level_values(level)
            if "Close" in level_values:
                df_cleaned.columns = level_values
                found = True
                break
        if not found:
            df_cleaned.columns = [col[0] if col[0] in ["Close", "Open", "High", "Low", "Volume", "Adj Close"] else col[1] for col in df_cleaned.columns]

    if isinstance(df_cleaned["Close"], pd.DataFrame):
        df_cleaned["Close"] = df_cleaned["Close"].iloc[:, 0]

    df_cleaned = df_cleaned.sort_index()
    df_cleaned = df_cleaned.dropna(subset=["Close"])
    df_cleaned["Close"] = pd.to_numeric(df_cleaned["Close"], errors="coerce")
    df_cleaned = df_cleaned.dropna(subset=["Close"])
    return df_cleaned


def compute_rsi(series: pd.Series, period: int = 14) -> pd.Series:
    """
    Calculates the 14-period Relative Strength Index (Wilder's Smoothing).
    """
    delta = series.diff()
    gain = delta.clip(lower=0)
    loss = -delta.clip(upper=0)
    avg_gain = gain.ewm(alpha=1.0 / period, adjust=False, min_periods=period).mean()
    avg_loss = loss.ewm(alpha=1.0 / period, adjust=False, min_periods=period).mean()
    rs = avg_gain / (avg_loss + 1e-9)
    return 100.0 - (100.0 / (1.0 + rs))


def engineer_multivariate_features(df: pd.DataFrame) -> pd.DataFrame:
    """
    Calculates stationary multivariate features:
    1. Log_Return: np.log(Close / Close.shift(1))
    2. RSI_14: 14-day Wilder RSI
    3. SMA_20_Ratio: Close / Close.rolling(20).mean()
    4. Volatility_10: Log_Return.rolling(10).std()
    5. Target_Next_Return: Log_Return.shift(-1) (Return of session T+1)
    """
    data = df.copy()
    data["Log_Return"] = np.log(data["Close"] / data["Close"].shift(1))
    data["RSI_14"] = compute_rsi(data["Close"], period=14)
    data["SMA_20_Ratio"] = data["Close"] / data["Close"].rolling(20).mean()
    data["Volatility_10"] = data["Log_Return"].rolling(10).std()
    data["Target_Next_Return"] = data["Log_Return"].shift(-1)
    data["Target_Next_Close"] = data["Close"].shift(-1)
    data["Target_Date"] = pd.Series(data.index, index=data.index).shift(-1)

    # Drop NaNs generated by rolling windows and the backward target shift
    data.dropna(subset=FEATURE_COLS + [TARGET_COL, "Target_Next_Close", "Target_Date"], inplace=True)
    return data


def download_market_data(
    ticker: str = "^NSEI",
    start_date: str = "2015-01-01",
    end_date: Optional[str] = None,
    save_raw: bool = True
) -> pd.DataFrame:
    """Downloads historical market data using yfinance and caches to data/raw/."""
    if end_date is None:
        end_date = datetime.now().strftime("%Y-%m-%d")

    print(f"[*] Downloading market data for '{ticker}' from {start_date} to {end_date}...")
    try:
        raw_df = yf.download(
            ticker,
            start=start_date,
            end=end_date,
            auto_adjust=True,
            progress=False
        )
    except Exception as e:
        raise RuntimeError(f"yfinance download failed for {ticker}: {e}")

    df = clean_market_data(raw_df, ticker=ticker)

    if save_raw:
        safe_ticker = ticker.replace("^", "").replace(".", "_").lower()
        raw_filepath = os.path.join(DATA_RAW_DIR, f"{safe_ticker}_raw.csv")
        df.to_csv(raw_filepath)
        print(f"[+] Raw data saved: {raw_filepath} ({len(df)} records)")

    return df


def prepare_multivariate_data(
    df: pd.DataFrame,
    time_step: int = 60,
    train_ratio: float = 0.8
) -> Dict[str, Any]:
    """
    Prepares multivariate train/test splits without lookahead data leakage.
    Scales features with feature_scaler and targets with target_scaler.
    """
    feat_df = engineer_multivariate_features(df)
    n_samples = len(feat_df)
    split_idx = int(n_samples * train_ratio)

    train_df = feat_df.iloc[:split_idx].copy()
    test_df = feat_df.iloc[split_idx:].copy()

    # Fit scalers strictly on training partition
    feature_scaler = MinMaxScaler(feature_range=(0, 1))
    target_scaler = MinMaxScaler(feature_range=(-1, 1))

    train_X_scaled = feature_scaler.fit_transform(train_df[FEATURE_COLS])
    # The final training row's label reaches into the test period, so exclude
    # it from target-scaler fitting and model training.
    train_y_scaled = target_scaler.fit_transform(train_df.iloc[:-1][[TARGET_COL]]).flatten()

    test_X_scaled = feature_scaler.transform(test_df[FEATURE_COLS])
    test_y_scaled = target_scaler.transform(test_df[[TARGET_COL]]).flatten()

    # Train sequences
    X_train, y_train = [], []
    for i in range(time_step - 1, len(train_X_scaled) - 1):
        X_train.append(train_X_scaled[i - time_step + 1:i + 1])
        y_train.append(train_y_scaled[i])
    X_train, y_train = np.array(X_train), np.array(y_train)

    # Test sequences with context continuity from train
    test_full_X = np.vstack([train_X_scaled, test_X_scaled])
    X_test, y_test = [], []
    for i in range(split_idx, len(test_full_X)):
        X_test.append(test_full_X[i - time_step + 1:i + 1])
        y_test.append(test_y_scaled[i - split_idx])
    X_test, y_test = np.array(X_test), np.array(y_test)

    return {
        "feat_df": feat_df,
        "train_df": train_df,
        "test_df": test_df,
        "X_train": X_train,
        "y_train": y_train,
        "X_test": X_test,
        "y_test": y_test,
        "feature_scaler": feature_scaler,
        "target_scaler": target_scaler,
        "test_dates": test_df["Target_Date"].values,
        "test_closes": test_df["Target_Next_Close"].values,
        "test_base_closes": test_df["Close"].values,
        "test_target_returns": test_df[TARGET_COL].values
    }


def build_lstm_model(input_shape: Tuple[int, int] = (60, 4)) -> Sequential:
    """
    Builds a stacked Keras Sequential LSTM model for multivariate sequence input.
    Input shape: (batch_size, 60, 4) -> Output shape: (batch_size, 1)
    """
    model = Sequential([
        Input(shape=input_shape),
        LSTM(units=64, return_sequences=True),
        Dropout(0.2),
        LSTM(units=32, return_sequences=False),
        Dropout(0.2),
        Dense(units=16, activation="relu"),
        Dense(units=1, activation="linear")
    ])
    model.compile(optimizer="adam", loss="mean_squared_error", metrics=["mae"])
    return model


def evaluate_predictions(y_actual: np.ndarray, y_predicted: np.ndarray) -> Dict[str, float]:
    """Calculates evaluation metrics (RMSE, MAE, R², Directional Accuracy, and 1% Tolerance)."""
    rmse = float(np.sqrt(mean_squared_error(y_actual, y_predicted)))
    mae = float(mean_absolute_error(y_actual, y_predicted))
    r2 = float(r2_score(y_actual, y_predicted))

    # Tolerance accuracy (within 1% of actual price)
    tolerance = 0.01 * np.abs(y_actual)
    accurate_points = np.sum(np.abs(y_actual - y_predicted) <= tolerance)
    accuracy_1pct = float((accurate_points / len(y_actual)) * 100.0)

    # Directional Accuracy: did the prediction correctly predict whether price went up or down?
    directional_correct = np.sum(np.sign(np.diff(y_actual)) == np.sign(np.diff(y_predicted)))
    directional_accuracy = float((directional_correct / max(1, len(y_actual) - 1)) * 100.0)

    return {
        "rmse": rmse,
        "mae": mae,
        "r2": r2,
        "accuracy_1pct": accuracy_1pct,
        "directional_accuracy": directional_accuracy
    }


def predict_next_day(
    live_price: float,
    recent_df: pd.DataFrame,
    model: Any,
    feature_scaler: Any,
    target_scaler: Any,
    time_step: int = 60
) -> Dict[str, float]:
    """
    Performs real-time multivariate inference:
    1. Recomputes exact features using historical data + current live price tick.
    2. Takes the last 60 steps and scales them using feature_scaler.
    3. Runs model prediction to get the predicted Log Return.
    4. Converts predicted log return back into price:
       Tomorrow_Predicted_Price = live_price * np.exp(predicted_log_return)
    """
    df_work = recent_df.copy()
    if isinstance(df_work.columns, pd.MultiIndex):
        df_work.columns = df_work.columns.get_level_values(0)

    # Update or append current live price
    if not df_work.empty and df_work.index[-1].date() == datetime.now().date():
        df_work.iloc[-1, df_work.columns.get_loc("Close")] = live_price
    else:
        new_row = pd.DataFrame({"Close": [live_price]}, index=[pd.Timestamp.now()])
        df_work = pd.concat([df_work, new_row])

    # Calculate stationary features
    df_work["Log_Return"] = np.log(df_work["Close"] / df_work["Close"].shift(1))
    df_work["RSI_14"] = compute_rsi(df_work["Close"], period=14)
    df_work["SMA_20_Ratio"] = df_work["Close"] / df_work["Close"].rolling(20).mean()
    df_work["Volatility_10"] = df_work["Log_Return"].rolling(10).std()

    # Drop NaNs
    feat_slice = df_work[FEATURE_COLS].dropna()
    if len(feat_slice) < time_step:
        raise ValueError(f"Insufficient history after feature calculation: {len(feat_slice)} rows, need {time_step}")

    last_60 = feat_slice.iloc[-time_step:].copy()
    scaled_seq = feature_scaler.transform(last_60)
    input_tensor = scaled_seq.reshape(1, time_step, len(FEATURE_COLS))

    pred_scaled = model.predict(input_tensor, verbose=0)
    pred_log_return = float(target_scaler.inverse_transform(pred_scaled.reshape(-1, 1)).flatten()[0])

    # Price conversion: P_{t+1} = P_t * exp(predicted_log_return)
    tomorrow_predicted_price = float(live_price * np.exp(pred_log_return))
    expected_change = float(tomorrow_predicted_price - live_price)
    expected_pct = float((expected_change / live_price) * 100.0)

    # Current technicals snapshot
    latest_rsi = float(last_60["RSI_14"].iloc[-1])
    latest_sma_ratio = float(last_60["SMA_20_Ratio"].iloc[-1])
    latest_volatility = float(last_60["Volatility_10"].iloc[-1])

    return {
        "live_price": live_price,
        "predicted_log_return": pred_log_return,
        "tomorrow_predicted_price": tomorrow_predicted_price,
        "expected_change": expected_change,
        "expected_pct": expected_pct,
        "rsi_14": latest_rsi,
        "sma_20_ratio": latest_sma_ratio,
        "volatility_10": latest_volatility
    }


def train_and_save(
    ticker: str = "^NSEI",
    epochs: int = 35,
    batch_size: int = 32,
    patience: int = 6
) -> Dict[str, Any]:
    """
    End-to-end multivariate pipeline:
    Downloads data -> Engineers features -> Scales -> Trains LSTM ->
    Evaluates backtest -> Saves model.keras, feature_scaler.pkl, target_scaler.pkl.
    """
    safe_ticker = ticker.replace("^", "").replace(".", "_").lower()
    df = download_market_data(ticker=ticker, start_date="2015-01-01", save_raw=True)
    data_dict = prepare_multivariate_data(df, time_step=60, train_ratio=0.8)

    X_train, y_train = data_dict["X_train"], data_dict["y_train"]
    X_test, y_test = data_dict["X_test"], data_dict["y_test"]
    feature_scaler = data_dict["feature_scaler"]
    target_scaler = data_dict["target_scaler"]
    test_closes = data_dict["test_closes"]
    test_base_closes = data_dict["test_base_closes"]
    test_dates = data_dict["test_dates"]

    print(f"\n[*] Training Multivariate LSTM on {X_train.shape[0]} sequences (shape: {X_train.shape})...")
    model = build_lstm_model(input_shape=(60, len(FEATURE_COLS)))
    model.summary()

    callbacks = [EarlyStopping(monitor="val_loss", patience=patience, restore_best_weights=True, verbose=1)]
    model.fit(
        X_train, y_train,
        epochs=epochs,
        batch_size=batch_size,
        validation_split=0.1,
        callbacks=callbacks,
        verbose=1
    )

    # Evaluate on Test Partition
    pred_test_scaled = model.predict(X_test, verbose=0)
    pred_test_returns = target_scaler.inverse_transform(pred_test_scaled).flatten()
    actual_test_returns = target_scaler.inverse_transform(y_test.reshape(-1, 1)).flatten()

    # The label on day t is the return from close(t) to close(t+1).
    reconstructed_pred_prices = test_base_closes * np.exp(pred_test_returns)

    test_metrics = evaluate_predictions(test_closes, reconstructed_pred_prices)
    return_rmse = float(np.sqrt(mean_squared_error(actual_test_returns, pred_test_returns)))

    print(f"\n[+] Backtest Evaluation for {ticker}:")
    print(f"    - Directional Accuracy: {test_metrics['directional_accuracy']:.2f}%")
    print(f"    - Price RMSE: INR {test_metrics['rmse']:,.2f}")
    print(f"    - Price MAE:  INR {test_metrics['mae']:,.2f}")
    print(f"    - Price R²:   {test_metrics['r2']:.4f}")
    print(f"    - Accuracy (1%): {test_metrics['accuracy_1pct']:.2f}%")
    print(f"    - Log-Return RMSE: {return_rmse:.5f}")

    # Save artifacts
    model_save_path = os.path.join(MODELS_DIR, f"lstm_model_{safe_ticker}.keras") if ticker != "^NSEI" else os.path.join(MODELS_DIR, "lstm_model.keras")
    feature_scaler_path = os.path.join(MODELS_DIR, f"feature_scaler_{safe_ticker}.pkl") if ticker != "^NSEI" else os.path.join(MODELS_DIR, "feature_scaler.pkl")
    target_scaler_path = os.path.join(MODELS_DIR, f"target_scaler_{safe_ticker}.pkl") if ticker != "^NSEI" else os.path.join(MODELS_DIR, "target_scaler.pkl")
    default_scaler_alias = os.path.join(MODELS_DIR, "scaler.pkl")

    model.save(model_save_path)
    joblib.dump(feature_scaler, feature_scaler_path)
    joblib.dump(target_scaler, target_scaler_path)
    joblib.dump(feature_scaler, default_scaler_alias)

    # Save processed backtest CSV
    backtest_df = pd.DataFrame({
        "Date": test_dates,
        "Actual_Close": np.round(test_closes, 2),
        "Predicted_Close": np.round(reconstructed_pred_prices, 2),
        "Actual_Return": np.round(actual_test_returns, 5),
        "Predicted_Return": np.round(pred_test_returns, 5)
    })
    backtest_path = os.path.join(DATA_PROCESSED_DIR, f"{safe_ticker}_backtest.csv")
    backtest_df.to_csv(backtest_path, index=False)

    # Save metrics dictionary
    metrics_path = os.path.join(MODELS_DIR, f"{safe_ticker}_metrics.pkl")
    metrics_payload = {
        "artifact_version": ARTIFACT_VERSION,
        "ticker": ticker,
        "test_metrics": test_metrics,
        "return_rmse": return_rmse,
        "trained_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    }
    joblib.dump(metrics_payload, metrics_path)

    print(f"[+] Artifacts successfully saved to {MODELS_DIR}")
    return {
        "model": model,
        "feature_scaler": feature_scaler,
        "target_scaler": target_scaler,
        "test_metrics": test_metrics,
        "backtest_df": backtest_df
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Multivariate Log-Return LSTM Pipeline")
    parser.add_argument("--ticker", type=str, default="^NSEI", help="NSE asset ticker (default: ^NSEI)")
    parser.add_argument("--epochs", type=int, default=30, help="Training epochs")
    args = parser.parse_args()

    train_and_save(ticker=args.ticker, epochs=args.epochs)
